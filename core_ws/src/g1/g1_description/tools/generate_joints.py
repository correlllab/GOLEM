#!/usr/bin/env python3
"""Regenerate g1_description/joints.py from the G1 URDF in leprechaun_g1.

    python3 tools/generate_joints.py           # rewrite g1_description/joints.py
    python3 tools/generate_joints.py --check   # exit 1 if the committed file is stale

Joint limits come from the URDF. The motor order does not: the with-hand URDF
interleaves each hand's joints after its arm, so the DDS order is taken from
Unitree's SDK below and cross-checked against the body-only MJCF's actuators.
"""

import argparse
import pathlib
import sys
import xml.etree.ElementTree as ET

PKG = pathlib.Path(__file__).resolve().parents[1]
REPO = PKG.parents[3]
ASSETS = REPO / 'third_party' / 'leprechaun_g1' / 'assets' / 'g1_description'
URDF = ASSETS / 'g1_29dof_with_hand_rev_1_0.urdf'
MJCF_BODY = ASSETS / 'g1_29dof_rev_1_0.xml'
OUT = PKG / 'g1_description' / 'joints.py'

# rt/lowcmd / rt/lowstate motor order: G1JointIndex in
# unitree_sdk2_python/example/g1/low_level/g1_low_level_example.py.
BODY_ORDER = [
    'left_hip_pitch_joint', 'left_hip_roll_joint', 'left_hip_yaw_joint',
    'left_knee_joint', 'left_ankle_pitch_joint', 'left_ankle_roll_joint',
    'right_hip_pitch_joint', 'right_hip_roll_joint', 'right_hip_yaw_joint',
    'right_knee_joint', 'right_ankle_pitch_joint', 'right_ankle_roll_joint',
    'waist_yaw_joint', 'waist_roll_joint', 'waist_pitch_joint',
    'left_shoulder_pitch_joint', 'left_shoulder_roll_joint', 'left_shoulder_yaw_joint',
    'left_elbow_joint', 'left_wrist_roll_joint', 'left_wrist_pitch_joint',
    'left_wrist_yaw_joint',
    'right_shoulder_pitch_joint', 'right_shoulder_roll_joint', 'right_shoulder_yaw_joint',
    'right_elbow_joint', 'right_wrist_roll_joint', 'right_wrist_pitch_joint',
    'right_wrist_yaw_joint',
]

# rt/dex3/{left,right}/cmd HandCmd_ motor order: leprechaun_g1/assets/README.md.
HAND_ORDER = ['thumb_0', 'thumb_1', 'thumb_2', 'middle_0', 'middle_1', 'index_0', 'index_1']

HEADER = '''\
"""G1 29-DoF + Dex3-1 joint table.

GENERATED by tools/generate_joints.py from
leprechaun_g1/assets/g1_description/{urdf}.
Do not edit by hand; rerun the generator instead.

Limits are Unitree's model values, not measurements of our unit. In this URDF
the ankles and waist roll/pitch allow 35 Nm where the MJCF says 50 Nm; confirm
on hardware before relying on either.
"""

from typing import NamedTuple


class Joint(NamedTuple):
    name: str
    slot: int  # index into the DDS motor array (LowCmd_/LowState_ or HandCmd_/HandState_)
    lower: float  # rad
    upper: float  # rad
    velocity: float  # rad/s
    effort: float  # N*m


'''


def urdf_limits(path):
    limits = {}
    for joint in ET.parse(path).getroot().findall('joint'):
        if joint.get('type') != 'revolute':
            continue
        lim = joint.find('limit')
        limits[joint.get('name')] = tuple(
            float(lim.get(k)) for k in ('lower', 'upper', 'velocity', 'effort'))
    return limits


def mjcf_motor_order(path):
    return [motor.get('joint') for motor in ET.parse(path).getroot().iter('motor')]


def render():
    limits = urdf_limits(URDF)
    if mjcf_motor_order(MJCF_BODY) != BODY_ORDER:
        sys.exit(f'BODY_ORDER does not match the actuator order in {MJCF_BODY.name}')

    def block(var, names):
        missing = [n for n in names if n not in limits]
        if missing:
            sys.exit(f'{URDF.name} has no revolute joint(s): {missing}')
        rows = ''.join(
            f'    Joint({n!r}, {i}, {", ".join(repr(v) for v in limits[n])}),\n'
            for i, n in enumerate(names))
        return f'{var} = (\n{rows})\n'

    return (HEADER.format(urdf=URDF.name)
            + '# rt/lowcmd / rt/lowstate order.\n'
            + block('BODY', BODY_ORDER) + '\n'
            + '# rt/dex3/left/cmd / state order.\n'
            + block('LEFT_HAND', [f'left_hand_{j}_joint' for j in HAND_ORDER]) + '\n'
            + '# rt/dex3/right/cmd / state order.\n'
            + block('RIGHT_HAND', [f'right_hand_{j}_joint' for j in HAND_ORDER]))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true',
                        help='fail instead of writing if joints.py is stale')
    args = parser.parse_args()
    text = render()
    if args.check:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} is stale; rerun tools/generate_joints.py')
        print(f'{OUT.name} is up to date')
        return
    OUT.write_text(text)
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
