import importlib.util
import os
import re
import shutil
import sys
from glob import glob

from setuptools import find_packages, setup

package_name = 'golem_ros2_models'

# The models come from the repo's CL_Assets submodule, at ../../../CL_Assets from this file.
# colcon may run this file from core_ws/src/golem_ros2_models or (--symlink-install) from
# core_ws/build/golem_ros2_models, the same depth, so the relative path holds for both.
# data_files sources must be relative paths (colcon's ament_python builder asserts it).
HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS_REL = os.path.join('..', '..', '..', 'CL_Assets')
ASSETS = os.path.normpath(os.path.join(HERE, ASSETS_REL))
# generated files, rewritten from scratch on every build
STAGE = os.path.join(HERE, '_install_staging')

LFS_POINTER = b'version https://git-lfs'
MESH_REF = re.compile(r'<mesh\b[^>]*?\bfilename="([^"]*)"')
PACKAGE_URI = f'package://{package_name}/'
# the 12 Magpie finger hinges, which the H1-2's ROS copy fixes
H12_HINGES = 12


def fail(message):
    sys.exit(f'{package_name}: {message}')


def asset(*parts):
    '''A CL_Assets file, relative to HERE; the build stops if it is missing or an LFS pointer'''
    path = os.path.join(ASSETS, *parts)
    if not os.path.isfile(path):
        fail(f'{os.path.join("CL_Assets", *parts)} is missing ({path})')
    with open(path, 'rb') as f:
        if f.read(len(LFS_POINTER)) == LFS_POINTER:
            fail(f'{path} is a Git-LFS pointer, not the file: run `git lfs pull` in CL_Assets')
    return os.path.relpath(path, HERE)


def meshes(*parts, pattern):
    found = sorted(glob(os.path.join(ASSETS, *parts, pattern)))
    if not found:
        fail(f'no meshes match {os.path.join(ASSETS, *parts, pattern)}')
    return [asset(*parts, os.path.basename(path)) for path in found]


def read(rel_path):
    with open(os.path.join(HERE, rel_path)) as f:
        return f.read()


def check_meshes_exist(rel_path, text):
    '''
    Every mesh the CL_Assets URDF names, relative to its own directory, is installable (run
    after rewrite_meshes, which refuses any other form of mesh reference)
    '''
    directory = os.path.dirname(os.path.join(HERE, rel_path))
    for ref in MESH_REF.findall(text):
        asset(os.path.relpath(os.path.normpath(os.path.join(directory, ref)), ASSETS))


def rewrite_meshes(rel_path, text, prefixes):
    '''
    Replace each mesh filename prefix by its new one; the build stops unless every mesh
    reference in the file is rewritten exactly once
    '''
    references = len(MESH_REF.findall(text))
    rewritten = 0
    for old, new in prefixes.items():
        rewritten += text.count(f'filename="{old}')
        text = text.replace(f'filename="{old}', f'filename="{new}')
    if references == 0 or rewritten != references:
        fail(f'{rel_path}: rewrote {rewritten} of {references} mesh references; every mesh '
             f'path must start with one of {sorted(prefixes)}')
    return text


def ros_header(source):
    return (f'<!-- Generated by {package_name}/setup.py from CL_Assets/{source}: '
            'mesh URIs point into this package. Do not edit. -->\n')


def stage(robot, name, text):
    path = os.path.join(STAGE, robot, name)
    with open(path, 'w') as f:
        f.write(text)
    return os.path.relpath(path, HERE)


def gen_ros_urdf():
    '''CL_Assets/ros_assets/gen_ros_urdf.py, the H1-2's gripper transform (stdlib only)'''
    path = os.path.join(HERE, asset('ros_assets', 'gen_ros_urdf.py'))
    spec = importlib.util.spec_from_file_location('gen_ros_urdf', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


if not os.path.isdir(ASSETS):
    fail(f'expected the CL_Assets submodule at {ASSETS}, which does not exist. Build this '
         'package from <repo>/core_ws/src/golem_ros2_models with CL_Assets checked out '
         '(`git submodule update --init CL_Assets`).')

shutil.rmtree(STAGE, ignore_errors=True)
for robot in ('h12', 'g1'):
    os.makedirs(os.path.join(STAGE, robot))

# The H1-2: CL_Assets/ros_assets URDFs name meshes ../meshes/{h1_2,magpie}/; installed in
# h12/ beside meshes/ and meshes/magpie/
H12_PINOCCHIO = {'../meshes/h1_2/': 'meshes/', '../meshes/magpie/': 'meshes/magpie/'}
H12_ROS = {'../meshes/h1_2/': f'{PACKAGE_URI}h12/meshes/',
           '../meshes/magpie/': f'{PACKAGE_URI}h12/meshes/magpie/'}
h12_files = []
for name in ('h1_2_magpie.urdf', 'h1_2_magpie_sphere.urdf'):
    source = asset('ros_assets', name)
    text = read(source)
    h12_files.append(stage('h12', name, rewrite_meshes(source, text, H12_PINOCCHIO)))
    check_meshes_exist(source, text)
    if name == 'h1_2_magpie.urdf':
        gen = gen_ros_urdf()
        ros = gen.rigidify_gripper(rewrite_meshes(source, text, H12_ROS))
        fixed = len(re.findall(r'<joint name="[lr]g_(?:left|right)_hinge_[123]" type="fixed"',
                               ros))
        if fixed != H12_HINGES:
            fail(f'{source}: fixed {fixed} Magpie finger hinges, expected {H12_HINGES}')
        ros = ros_header('ros_assets/' + name) + ros
        gen.assert_well_formed(ros, 'h1_2_magpie_ros.urdf')
        h12_files.append(stage('h12', 'h1_2_magpie_ros.urdf', ros))
h12_files.append(asset('ros_assets', 'h1_2_magpie_sphere_collision.srdf'))

# The G1: CL_Assets/g1 URDFs name meshes meshes/; the Pinocchio copy installs verbatim in g1/
# beside meshes/. The ROS copy keeps the Dex3-1 joints articulated.
G1_MODEL = 'g1_29dof_with_hand_rev_1_0'
source = asset('g1', 'g1_description', G1_MODEL + '.urdf')
text = read(source)
g1_ros = rewrite_meshes(source, text, {'meshes/': f'{PACKAGE_URI}g1/meshes/'})
check_meshes_exist(source, text)
g1_ros = ros_header(f'g1/g1_description/{G1_MODEL}.urdf') + g1_ros
gen_ros_urdf().assert_well_formed(g1_ros, G1_MODEL + '_ros.urdf')
g1_sphere = asset('g1', 'g1_sphere.urdf')
if MESH_REF.findall(read(g1_sphere)):
    fail(f'{g1_sphere}: the G1 sphere model must have no mesh references')
g1_files = [
    source,
    stage('g1', G1_MODEL + '_ros.urdf', g1_ros),
    g1_sphere,
    asset('g1', 'g1_sphere_collision.srdf'),
    asset('g1', 'LICENSE.unitree_ros'),
]

share = 'share/' + package_name
setup(
    name=package_name,
    version='0.1.0',
    packages=find_packages(exclude=['test']),
    data_files=[
        ('share/ament_index/resource_index/packages', ['resource/' + package_name]),
        (share, ['package.xml']),
        (share + '/launch', glob('launch/*.launch.py')),
        (share + '/rviz', glob('rviz/*.rviz')),
        (share + '/h12', h12_files),
        (share + '/h12', ['licenses/LICENSE.unitree_ros']),
        (share + '/h12/meshes', meshes('meshes', 'h1_2', pattern='*.STL')),
        (share + '/h12/meshes/magpie', meshes('meshes', 'magpie', pattern='*.stl')),
        (share + '/g1', g1_files),
        (share + '/g1/meshes', meshes('g1', 'g1_description', 'meshes', pattern='*.STL')),
    ],
    install_requires=['setuptools'],
    zip_safe=True,
    maintainer='maxconway',
    maintainer_email='maxlconway@gmail.com',
    description="The H1-2's and the G1's robot models (URDFs, self-collision models, meshes) "
                'from CL_Assets',
    license='MIT',
    tests_require=['pytest'],
)
