#!/usr/bin/env python3
"""Writes the robot data files golem_safety and golem_upper_ik read.

Outputs, relative to the package: robots/h12.yaml and robots/g1.yaml.

Sources:

  H1-2  tools/h12_joint_limits.py (JOINT_NAMES, URDF_POSITION_LIMITS,
        URDF_VELOCITY_LIMITS, URDF_TORQUE_LIMITS). The H1-2 limits are this table,
        which is what the robot runs, not the URDF: shoulder roll is +-0.38 here
        and +-0.19 in h1_2_magpie.urdf.
  G1    g1_description.joints.BODY and g1_description.layout.

Run it where g1_description imports (the G1-mode ros container, after the workspace is
built and sourced):

  python3 /home/code/core_ws/src/golem_safety/tools/generate_robot_data.py
"""
from pathlib import Path
import sys

import yaml

PACKAGE = Path(__file__).resolve().parents[1]

ROBOT_FILE_HEADER = (
    '# Generated by tools/generate_robot_data.py from {source}. Do not edit by hand.\n'
)


def number(value):
    """A float as YAML text that reads back as the same float."""
    return repr(float(value))


def h12_joints():
    """(name, slot, low, high, velocity, effort) per body joint, from tools/h12_joint_limits.py."""
    import h12_joint_limits as table

    return [
        (name, slot, limits['low'], limits['high'], velocity, effort)
        for slot, (name, limits, velocity, effort) in enumerate(zip(
            table.JOINT_NAMES, table.URDF_POSITION_LIMITS,
            table.URDF_VELOCITY_LIMITS, table.URDF_TORQUE_LIMITS))
    ]


def g1_joints():
    from g1_description.joints import BODY

    return [(j.name, j.slot, j.lower, j.upper, j.velocity, j.effort) for j in BODY]


def robot_text(source, facts, joints):
    lines = [ROBOT_FILE_HEADER.format(source=source)]
    lines.append(f'robot: {facts["robot"]}\n')
    lines.append(f'mode_machine: {facts["mode_machine"]}  '
                 '# the value /lowstate reports and every command carries\n')
    lines.append(f'mode_pr: {facts["mode_pr"]}\n')
    lines.append(f'motor_slots: {facts["motor_slots"]}  '
                 '# length of the LowCmd/LowState motor arrays\n')
    lines.append(f'modes: [{", ".join(facts["modes"])}]\n')
    lines.append(f'lower_slots: {list(facts["lower_slots"])}  # inclusive\n')
    lines.append(f'upper_slots: {list(facts["upper_slots"])}  # inclusive\n')
    lines.append('# Body joints in slot order. position is [low, high] in rad, velocity in\n'
                 '# rad/s, effort in N*m.\n')
    lines.append('joints:\n')
    for name, slot, low, high, velocity, effort in joints:
        lines.append(
            f'  - {{name: {name}, slot: {slot}, position: [{number(low)}, {number(high)}], '
            f'velocity: {number(velocity)}, effort: {number(effort)}}}\n')
    return ''.join(lines)


def check_round_trip(text, facts, joints):
    """Fails unless the text reads back as exactly the source values."""
    data = yaml.safe_load(text)
    expected_joints = [
        {'name': name, 'slot': slot, 'position': [float(low), float(high)],
         'velocity': float(velocity), 'effort': float(effort)}
        for name, slot, low, high, velocity, effort in joints
    ]
    expected = {**facts, 'lower_slots': list(facts['lower_slots']),
                'upper_slots': list(facts['upper_slots']), 'joints': expected_joints}
    if data != expected:
        sys.exit(f'robot file for {facts["robot"]} does not read back as its source')


def main():
    from g1_description import layout

    h12_facts = {
        'robot': 'h12', 'mode_machine': 6, 'mode_pr': 0, 'motor_slots': 35,
        'modes': ['full_body_mode', 'split_mode'],
        'lower_slots': (0, 11), 'upper_slots': (12, 26),
    }
    g1_facts = {
        'robot': 'g1', 'mode_machine': 5, 'mode_pr': layout.MODE_PR,
        'motor_slots': layout.LOWCMD_MOTOR_SLOTS,
        'modes': ['split_mode', 'full_body_mode'],
        'lower_slots': (layout.LEG_SLOTS.start, layout.LEG_SLOTS.stop - 1),
        # the waist and both arms
        'upper_slots': (layout.WAIST_SLOTS.start, layout.RIGHT_ARM_SLOTS[-1]),
    }
    robots = [
        ('h12', 'tools/h12_joint_limits.py', h12_facts, h12_joints()),
        ('g1', 'g1_description.joints.BODY', g1_facts, g1_joints()),
    ]

    (PACKAGE / 'robots').mkdir(exist_ok=True)
    for robot, source, facts, joints in robots:
        text = robot_text(source, facts, joints)
        check_round_trip(text, facts, joints)
        (PACKAGE / 'robots' / f'{robot}.yaml').write_text(text)


if __name__ == '__main__':
    main()
