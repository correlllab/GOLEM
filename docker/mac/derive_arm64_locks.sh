#!/usr/bin/env bash
# Derive the Mac images' arm64 Python locks (docker/locks/*-arm64*.txt) from the
# x86 images' amd64 locks, so the two platforms resolve the same versions.
#
# Usage: docker/mac/derive_arm64_locks.sh
#   Rewrites every docker/locks/{base,robocasa,ros}-arm64*.txt from its amd64
#   twin. Run it after any amd64 lock changes, then rebuild the Mac images
#   (docker/scripts/docker_build.sh on the Mac) to check the result resolves.
# The rewrite, line by line:
#   - drops the CUDA-only wheels (nvidia-*, cuda-*, triton): the Mac images
#     run torch on the CPU;
#   - turns torch's and torchvision's +cu130 local version into +cpu (the
#     CPU index, download.pytorch.org/whl/cpu, has the same versions for
#     linux/aarch64);
#   - pins open3d 0.18.0: 0.19.0 has no linux/aarch64 wheel for Python 3.10;
#   - renames the -c references to the arm64 files.
# Exit status: 0, or 1 when an amd64 lock is missing.
set -euo pipefail
LOCKS=$(cd "$(dirname "$0")/../locks" && pwd)
for src in "$LOCKS"/{base,robocasa,ros}-amd64*.txt; do
    [ -f "$src" ] || { echo "ERROR: no amd64 locks in $LOCKS" >&2; exit 1; }
    dst=${src/-amd64/-arm64}
    {
        echo '# Generated by docker/mac/derive_arm64_locks.sh from'
        echo "# $(basename "$src"); edit the amd64 lock and rerun the script."
        grep -vE '^(nvidia-[a-z0-9-]+|cuda-[a-z0-9-]+|triton)==' "$src" \
            | sed -e 's/^\(torch\(vision\)\{0,1\}==[^+]*\)+cu130$/\1+cpu/' \
                  -e 's/^open3d==0\.19\.0$/open3d==0.18.0/' \
                  -e 's/^-c \(.*\)-amd64\.txt$/-c \1-arm64.txt/'
    } > "$dst"
done
