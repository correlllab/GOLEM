"""Register the Unitree H1-2 with its MAGPIE grippers as a robosuite robot, and place it.

Importing this module makes ``robots="H1_2"`` resolvable; make_kitchen_env
installs the RoboCasa placement patch (robosuite_common), which positions the
legged robot by its pelvis free joint (RoboCasa's own placement writes
mobile-base joints this robot lacks), and builds a task env.
place_robot_collision_free keeps the robot clear of the floor and the fixtures
by a margin.

The models are CL_Assets/robosuite_assets, generated by its build_assets.py.
The robot keeps its floating base and all 27 actuators: the ROS stack drives
them over DDS, and robosuite's controllers are never stepped (the sim loop
calls mujoco.mj_step itself). robosuite and robocasa are installed only in the
robocasa image.
"""
import os

import numpy as np

from robosuite.models.grippers import register_gripper
from robosuite.models.grippers.gripper_model import GripperModel
from robosuite.models.robots.manipulators.legged_manipulator_model import (
    LeggedManipulatorModel,
)
from robosuite.robots import register_robot_class

import robosuite_common
from robosuite_common import ROBOT_PREFIXES, backward_dir, place_robot_clear, robot_env_contacts

_ASSETS = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "CL_Assets", "robosuite_assets")
)
ROBOT_XML = os.path.join(_ASSETS, "robots", "h1_2", "robot.xml")
GRIPPER_RIGHT_XML = os.path.join(_ASSETS, "grippers", "magpie_right_gripper.xml")
GRIPPER_LEFT_XML = os.path.join(_ASSETS, "grippers", "magpie_left_gripper.xml")

# The robot MJCF's head camera, whose optical frame is the URDF head_camera_link.
HEAD_CAMERA = "head_cam"

# robosuite's init_qpos of the 27 actuated joints; h12_mujoco puts the robot in
# its own spawn pose after the reset.
_INIT_QPOS = np.zeros(27)


class _MagpieGripperBase(GripperModel):
    """Define the MAGPIE 4-bar parallel-jaw gripper's robosuite properties.

    Two independently actuated cranks (finger_joint1/2) close the jaws through
    the MJCF's <equality><connect> 4-bar linkage. MagpieHandBridge drives them;
    env.step() is never called, so the robosuite action interface is inert.
    """

    def format_action(self, action):
        """Return action unchanged."""
        return action

    @property
    def init_qpos(self):
        """Return zeros for the gripper's 6 hinges (3 per finger)."""
        return np.zeros(6)

    @property
    def speed(self):
        """Return robosuite's gripper speed (unused: env.step() is never called)."""
        return 0.2

    @property
    def dof(self):
        """Return the 2 actuated cranks."""
        return 2

    @property
    def _important_geoms(self):
        """Return the finger pad geoms robosuite's grasp checks use."""
        return {
            "left_finger": ["left_pad1", "left_pad2", "left_pad3", "left_pad4"],
            "right_finger": ["right_pad1", "right_pad2", "right_pad3", "right_pad4"],
            "left_fingerpad": ["left_pad4"],
            "right_fingerpad": ["right_pad4"],
        }


@register_gripper
class MagpieRightGripper(_MagpieGripperBase):
    """Load the right MAGPIE gripper."""

    def __init__(self, idn=0):
        """Load magpie_right_gripper.xml."""
        super().__init__(GRIPPER_RIGHT_XML, idn=idn)


@register_gripper
class MagpieLeftGripper(_MagpieGripperBase):
    """Load the left MAGPIE gripper."""

    def __init__(self, idn=0):
        """Load magpie_left_gripper.xml."""
        super().__init__(GRIPPER_LEFT_XML, idn=idn)


@register_robot_class("LeggedRobot")
class H1_2(LeggedManipulatorModel):
    """Model the full-legged Unitree H1-2 with two MAGPIE grippers.

    It keeps the pelvis free joint and all 27 actuators, so the ROS stack drives
    every joint over DDS and the legs walk on floor contact.

    The base is NullBase, not NoActuationBase: NoActuationBase is a
    MobileBaseModel, whose add_mobile_base() deletes the pelvis <freejoint> and
    welds the robot to the world. NullBase's add_null_base() leaves the robot
    tree and its free joint as they are.
    """

    arms = ["right", "left"]

    def __init__(self, idn=0):
        """Load the robot MJCF and place its head camera as the real robot's."""
        super().__init__(ROBOT_XML, idn=idn)
        # The calibrated colour optical pose and intrinsics, and a depth camera
        # at the depth optical pose (realsense_profile.yaml). The names carry
        # the robot prefix by now.
        import realsense_profile

        realsense_profile.place_profiled_cameras(
            self.worldbody, f"{self.naming_prefix}{HEAD_CAMERA}",
            realsense_profile.load_profile()["cameras"]["head"])

    @property
    def default_base(self):
        """Return NullBase, which keeps the pelvis free joint."""
        return "NullBase"

    @property
    def default_gripper(self):
        """Return the MAGPIE gripper of each arm."""
        return {"right": "MagpieRightGripper", "left": "MagpieLeftGripper"}

    @property
    def default_controller_config(self):
        """Return a placeholder robosuite requires; it is never used.

        robosuite finds no default_h1_2.json and falls back to its BASIC
        composite controller, which is never stepped.
        """
        return {"right": "default_h1", "left": "default_h1"}

    @property
    def init_qpos(self):
        """Return robosuite's initial joint positions (all 0)."""
        return _INIT_QPOS

    @property
    def base_xpos_offset(self):
        """Return robosuite's base offsets (m) for its bins, empty and table arenas."""
        return {
            "bins": (-0.5, -0.1, 0.0),
            "empty": (-0.29, 0, 0.0),
            "table": lambda table_length: (-0.26 - table_length / 2, 0, 0.0),
        }

    @property
    def top_offset(self):
        """Return robosuite's top offset (m)."""
        return np.array((0, 0, 1.0))

    @property
    def _horizontal_radius(self):
        """Return robosuite's horizontal radius (m)."""
        return 0.5

    @property
    def arm_type(self):
        """Return bimanual."""
        return "bimanual"

    @property
    def _eef_name(self):
        """Return each arm's end-effector body, where its gripper is merged."""
        return {"right": "right_hand", "left": "left_hand"}


def _robot_env_gap(model, data, margin, prefixes=ROBOT_PREFIXES, floor_prefix="floor"):
    """Return the smallest distance (m) from a robot geom to a non-floor environment geom.

    Capped at margin, negative when they overlap. One collision pass with the
    robot geoms' contact margin raised to margin finds every pair closer than
    that; mj_geomDistance then measures each pair, since contact distances
    under an inflated margin are unreliable (box-box can report tens of cm of
    false penetration). Floors (bodies or geoms named floor*) are skipped: the
    feet always stand within a few cm of them. The kinematics must be current;
    the contacts are recomputed with the model's own margins before returning.
    """
    import mujoco

    bodies = [mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_BODY, b) or "" for b in model.geom_bodyid]
    geoms = [mujoco.mj_id2name(model, mujoco.mjtObj.mjOBJ_GEOM, g) or "" for g in range(model.ngeom)]
    robot = np.array([b.startswith(prefixes) for b in bodies])
    floor = np.array([b.startswith(floor_prefix) or g.startswith(floor_prefix)
                      for b, g in zip(bodies, geoms)])
    saved = model.geom_margin.copy()
    saved_flags = model.opt.disableflags
    try:
        model.geom_margin[robot] = np.maximum(saved[robot], margin)
        # The midphase culls pairs in multi-geom bodies by bounding volumes that
        # ignore the inflated margin, which would drop near pairs.
        model.opt.disableflags = saved_flags | mujoco.mjtDisableBit.mjDSBL_MIDPHASE
        mujoco.mj_collision(model, data)
        pairs = set()
        for i in range(data.ncon):
            g1, g2 = int(data.contact[i].geom1), int(data.contact[i].geom2)
            if robot[g1] != robot[g2] and not (floor[g1] or floor[g2]):
                pairs.add((g1, g2))
        fromto = np.zeros(6)
        gap = min([margin] + [mujoco.mj_geomDistance(model, data, g1, g2, margin, fromto)
                              for g1, g2 in pairs])
    finally:
        model.geom_margin[:] = saved
        model.opt.disableflags = saved_flags
        mujoco.mj_collision(model, data)
    return gap


def _overlaps_behind(model, data, pos, back):
    """Return whether the robot overlaps an environment geom on the back side of pos (xy)."""
    return any(np.dot(np.asarray(c.pos[:2]) - pos[:2], back[:2]) > 0.0
               for c in robot_env_contacts(model, data))


def _placed_gap(env, pos, base_quat, clearance, margin, poses, back):
    """Return (gap, blocked) for the base at pos over the current joints and every pose in poses.

    poses are (qpos indices, values) pairs. gap is the smallest
    _robot_env_gap; blocked means some pose overlaps a geom behind the base.
    Leaves the robot at pos in its current joint state.
    """
    model = env.sim.model._model
    data = env.sim.data._data
    gap, blocked = margin, False
    for idx, values in ((None, None), *poses):
        if idx is not None:
            spawn = data.qpos[idx].copy()
            data.qpos[idx] = values
        place_robot_clear(env, pos, base_quat, clearance)
        pose_gap = _robot_env_gap(model, data, margin)
        if pose_gap < 0.0:
            blocked = blocked or _overlaps_behind(model, data, pos, back)
        gap = min(gap, pose_gap)
        if idx is not None:
            data.qpos[idx] = spawn
    if poses:
        place_robot_clear(env, pos, base_quat, clearance)
    return gap, blocked


def place_robot_collision_free(env, base_pos, base_quat, step=0.02, max_iters=50,
                               clearance=0.02, extra_backoff=0.0, margin=0.0, poses=()):
    """Place the robot at its spawn with margin (m) of free space to every non-floor environment geom.

    From base_pos, base_quat (wxyz) it places the robot clearance (m) above the
    floor, then backs it off (the robot's -x) in step (m) increments, up to
    max_iters, until the gap reaches margin; the orientation never changes.
    margin 0 only removes overlap (1 mm minimum, so nothing starts touching).
    poses are extra (qpos indices, values) joint configurations in which the
    margin must hold too; the robot is left in its current joint state.

    If the margin is not reached, or the robot starts overlapping something
    behind it, it restores the position with the widest gap and warns, so the
    sim still starts and never ends up on the far side of a fixture.
    extra_backoff (m) then backs it further into open floor while the margin
    holds, for Nav2, which needs a free start cell.
    """
    back = backward_dir(base_quat)
    margin = max(margin, 1e-3)   # geoms that merely touch still make contacts
    pos = np.array(base_pos, dtype=float)
    best_pos, best_gap = None, None
    for i in range(max_iters + 1):
        gap, blocked = _placed_gap(env, pos, base_quat, clearance, margin, poses, back)
        if i and blocked:
            break
        if best_gap is None or gap > best_gap:
            best_gap, best_pos = gap, pos.copy()
        if gap >= margin:
            if i:
                print(f"[h1_2_robosuite] moved robot back {i * step:.2f} m for "
                      f"{margin:.2f} m spawn clearance")
            if extra_backoff > 0.0:
                last_clear, moved = pos.copy(), 0.0
                for _ in range(int(extra_backoff / step)):
                    pos[:2] += step * back[:2]
                    if _placed_gap(env, pos, base_quat, clearance, margin, poses, back)[0] < margin:
                        break
                    last_clear, moved = pos.copy(), moved + step
                place_robot_clear(env, last_clear, base_quat, clearance)
                if moved:
                    print(f"[h1_2_robosuite] backed robot {moved:.2f} m further into open floor (nav spawn)")
            return
        pos[:2] += step * back[:2]
    place_robot_clear(env, best_pos, base_quat, clearance)
    print(f"[h1_2_robosuite] WARNING: best spawn clearance {best_gap:.3f} m is below the "
          f"requested {margin:.2f} m (searched {i * step:.2f} m back); keeping the "
          f"widest-gap position")


# RoboCasa's placement offset (m): the pelvis z. The soles are 1.041 m below
# the pelvis at init_qpos, so 1.05 keeps them ~1 cm clear until h12_mujoco
# re-places the robot.
POS_OFFSET = (0.0, 0.0, 1.05)


def make_kitchen_env(env_name, layout_ids=None, style_ids=None, seed=None, **kwargs):
    """Return the task env env_name around an H1_2 (robosuite_common.make_kitchen_env)."""
    return robosuite_common.make_kitchen_env(H1_2, POS_OFFSET, env_name, layout_ids, style_ids, seed,
                                             **kwargs)
